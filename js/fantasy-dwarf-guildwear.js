function dwarfGuildWear(unit) {
  const type = unit.type?.split('~',1)[0] || '';
  const recruit = unit.rec || unit.gx;
  let key = recruit?.cls;
  let rank = 'recruit';
  if (!key && (type === 'hero' || type.startsWith('hero_'))) {
    key = type === 'hero' ? unit.hero?.clsKey : type.slice(5);
    rank = 'hero';
  } else if (!key && type.startsWith('gm_')) {
    key = type.slice(3);
    rank = 'master';
  }
  const style = DWARF_GUILD_STYLES[key || type];
  if (!style) return null;
  const branch = GBR[recruit?.cls]?.some(entry => entry.k === recruit.br) ? recruit.br : '';
  const veteran = !!branch && recruit.lvl >= GBR_VET;
  return { key:key || type, style, rank, branch, veteran, armored:!!recruit?.armor };
}

function dwarfGuildCacheKey(wear) {
  return wear ? `${wear.key}:${wear.rank}:${wear.branch}:${Number(wear.veteran)}:${Number(wear.armored)}` : '';
}

function dwarfGuildShoulder(wear) {
  const {coat,plate,edge,material,accent}=wear.style;
  const branch=DWARF_GUILD_BRANCHES[wear.branch];
  if(wear.rank==='master')return [null,coat,shade(plate,.13),accent,material];
  if(wear.rank==='recruit'&&!wear.armored){
    return [null,coat,shade(coat,.13),branch?.tone||shade(coat,.37),'leather'];
  }
  return [null,coat,plate,branch?.tone||edge,material];
}

function drawGuildInsignia(draw, wear, view) {
  const badge = DWARF_GUILD_BRANCHES[wear.branch];
  if (!badge) return;
  const x = view === 'E' ? 2.5 : 0, y = view === 'N' ? 5 : 7;
  const mark = (dx,dy,w,h) => draw.rect(x+dx,y+dy,w,h,badge.tone);
  draw.rect(x-1.5,y-1,3,3,'#322820');
  switch (badge.sign) {
    case 'shield':
      mark(-1,-.5,2,1); mark(-.5,.5,1,1); break;
    case 'slash':
      mark(.5,-.5,.5,1); mark(0,0,.5,1); mark(-.5,.5,.5,1); break;
    case 'sight':
      mark(-1,0,2,.5); mark(-.25,-.5,.5,1.5); break;
    case 'leaves':
      mark(-1,-.5,.5,1); mark(0,.5,1,.5); mark(.5,0,.5,.5); break;
    case 'crescent':
      mark(-.5,-.5,1,.5); mark(-1,0,.5,1); mark(-.5,1,1,.5); break;
    case 'hook':
      mark(0,-.5,1,.5); mark(.5,0,.5,1); mark(-.5,.5,1,.5); break;
    case 'spark':
      mark(.5,-.5,.5,.5); mark(-.5,0,1,1); mark(0,1,.5,.5); break;
    case 'cross':
      mark(-.25,-.5,.5,2); mark(-1,0,2,.5); break;
  }
  if (wear.veteran) draw.rect(x-.5,y+1.5,1,.5,'#e1c98e');
}


